"""G3: audit numeric literals in the paper's main-text sections.

    python3 results/G3_number_audit.py            # prints the report
    python3 results/G3_number_audit.py --write     # also writes the .md

Scope (TASKS5 G3.4, fixed by results/G1_pagebudget.md "structure decisions"):
    paper/sections/experiments.tex
    paper/sections/results.tex
    paper/sections/model.tex

The requirement is that the count of NON-WHITELISTED experiment-number
literals is zero: every experiment number in the running text must come from a
macro of paper/sections/numbers.tex (generated by results/G3_gen_numbers.py).

Method.  LaTeX comments are stripped first (an unescaped '%' to end of line),
because a comment is not visible text.  What remains is masked into regions,
and every numeric literal is classified by the region it falls in:

  structure      argument of \\label, \\ref, \\input, \\includegraphics,
                 \\begin, \\end, \\newcommand, \\setlength: not prose
  citation       optional argument of \\citep / \\citet, i.e. a page or
                 theorem locator such as [Theorem~3] or [Definition~2.3]
  length         a number carrying a TeX length unit or a \\...width factor
                 (0.66\\textwidth, 4pt): typesetting, not a measurement
  K value/index  a budget K or a sub/superscript index: K=5, L_{30}, V_j
  theory const   in results.tex / model.tex, a literal inside math mode:
                 these are closed-form coefficients and model constants whose
                 status is set by the oracle scripts named in those files'
                 status comments, not experiment measurements
  proper name    a digit inside a fixed list of names (ROUGE-1, digits20)
  VIOLATION      anything else

The "theory const" allowance is deliberately NOT extended to
experiments.tex: there, any math-mode literal that is not a K value is a
violation, which is what makes the zero-count meaningful.

Two generated files are reported separately and are not part of the count:
paper/sections/numbers.tex (the macro definitions) and
paper/sections/EXP_table.tex (a generated copy of results/EXP_table.tex,
produced by results/EXP_table_build.py).  Their numbers are scripted, not
hand-typed, which is the whole reason the section text may print them.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SEC = os.path.join(ROOT, 'paper', 'sections')

SCANNED = ['experiments.tex', 'results.tex', 'model.tex']
# Not part of the required count (TASKS5 G3.4 fixes the scope above), but
# written under the same rule, so it is reported for information.
EXTRA = ['appendix_experiments.tex']
GENERATED = ['numbers.tex', 'EXP_table.tex']

# Proper names that contain a digit.  Kept as an explicit, short list so the
# rule cannot quietly swallow a measurement.
PROPER_NAMES = ['ROUGE-1', 'digits20', 'email-Eu-core']

NUM = re.compile(r'(?<![A-Za-z0-9])(\d+(?:\.\d+)?|\.\d+)')
UNIT = re.compile(r'\s*(pt|em|ex|cm|mm|in|bp|sp|\\textwidth|\\linewidth|'
                  r'\\columnwidth|\\textheight|\\baselineskip)\b')

STRUCT_CMDS = (r'label|ref|eqref|pageref|autoref|input|include|includegraphics|'
               r'begin|end|newcommand|renewcommand|setlength|bibliography|'
               r'bibliographystyle|usepackage|documentclass|caption')


def strip_comments(text):
    """Remove LaTeX comments, keeping character offsets stable (blank them)."""
    out = []
    for line in text.split('\n'):
        i, n, cut = 0, len(line), None
        while i < n:
            if line[i] == '\\':
                i += 2
                continue
            if line[i] == '%':
                cut = i
                break
            i += 1
        out.append(line if cut is None else line[:cut] + ' ' * (n - cut))
    return '\n'.join(out)


def spans(text, pattern):
    return [(m.start(), m.end()) for m in re.finditer(pattern, text)]


def region_map(text):
    """Return a list of (start, end, kind) regions, later ones win."""
    regions = []
    # structural commands and their arguments (one optional + one mandatory)
    for m in re.finditer(r'\\(?:' + STRUCT_CMDS + r')\s*(\[[^\]]*\])?'
                         r'(\{[^{}]*\})?(\{[^{}]*\})?', text):
        regions.append((m.start(), m.end(), 'structure'))
    # citation locators: the optional argument of \citep / \citet
    for m in re.finditer(r'\\cite[a-z]*\s*\[[^\]]*\]', text):
        regions.append((m.start(), m.end(), 'citation'))
    # math mode
    for m in re.finditer(r'\\\[.*?\\\]', text, re.S):
        regions.append((m.start(), m.end(), 'math'))
    for m in re.finditer(r'(?<!\\)\$(?:\\.|[^$\\])*\$', text, re.S):
        regions.append((m.start(), m.end(), 'math'))
    # proper names
    for name in PROPER_NAMES:
        for m in re.finditer(re.escape(name), text):
            regions.append((m.start(), m.end(), 'proper'))
    return regions


def kind_at(regions, pos):
    kinds = [k for s, e, k in regions if s <= pos < e]
    for pref in ('structure', 'citation', 'proper', 'math'):
        if pref in kinds:
            return pref
    return None


K_CONTEXT = re.compile(
    r'(K\s*(=|\\ge|\\geq|\\le|\\leq|\\in|\\to)\s*\\?[{\\a-z]*$)'
    r'|(_\{?$)|(\^\{?$)'
    r'|((L|\\rho|\\eta|V|U|S|q|k|a)\s*_\s*\{?$)')


def classify(path, text, regions, m):
    lit = m.group(1)
    start = m.start(1)
    before = text[max(0, start - 24):start]
    after = text[m.end(1):m.end(1) + 16]
    kind = kind_at(regions, start)

    if kind == 'structure':
        return 'structure', 'label / input / includegraphics / environment'
    if kind == 'citation':
        return 'citation', 'page or theorem locator of a citation'
    if kind == 'proper':
        return 'proper name', 'digit inside a proper name'
    if UNIT.match(after):
        return 'length', 'typesetting length or width factor'
    if K_CONTEXT.search(before.rstrip() if before.rstrip().endswith(('_', '^'))
                        else before):
        return 'K value/index', 'budget K or a sub/superscript index'
    # sub/superscript written without braces, e.g. L_7 or V_0
    if before.rstrip().endswith(('_', '^')):
        return 'K value/index', 'sub/superscript index'
    if kind == 'math':
        if os.path.basename(path) == 'experiments.tex':
            return 'VIOLATION', 'math-mode literal in the experiments section'
        return 'theory const', ('closed-form coefficient or model constant in '
                                'math mode; status set by the oracle scripts '
                                'named in the file, not an experiment number')
    return 'VIOLATION', 'numeric literal in visible prose'


def scan_text(fname, raw):
    text = strip_comments(raw)
    regions = region_map(text)
    hits = []
    for m in NUM.finditer(text):
        cat, why = classify(fname, text, regions, m)
        line = text.count('\n', 0, m.start(1)) + 1
        ctx = text[max(0, m.start(1) - 34):m.end(1) + 22]
        ctx = ' '.join(ctx.split())
        hits.append(dict(file=fname, line=line, lit=m.group(1), cat=cat,
                         why=why, ctx=ctx))
    return hits


def scan(fname):
    with open(os.path.join(SEC, fname)) as fh:
        return scan_text(fname, fh.read())


# --------------------------------------------------------------------------
# Negative control.  A whitelist is only worth something if it still fires on
# real violations, so the audit checks itself on synthetic input every run and
# the result is printed in the report.
# --------------------------------------------------------------------------
SELFTEST_BAD = r"""
The median ratio is 0.971 at $\etasel = 2.0$, over 120 runs.
% a comment mentioning 0.42 must NOT be reported
The bound falls to 0.008 on one network.
"""
SELFTEST_OK = r"""
At $K=\ETwoKMain$ the bound $L_{30}(\etasel)$ and the index $V_0$ hold.
\includegraphics[width=0.66\textwidth]{figures/aux_p_vs_eta.pdf}
See \citep[Theorem~3]{horel2016maximization} and the ROUGE-1 F score.
\label{sec:experiments2}
"""


def selftest():
    bad = [h for h in scan_text('experiments.tex', SELFTEST_BAD)
           if h['cat'] == 'VIOLATION']
    ok = [h for h in scan_text('experiments.tex', SELFTEST_OK)
          if h['cat'] == 'VIOLATION']
    caught = sorted(h['lit'] for h in bad)
    return caught == ['0.008', '0.971', '120', '2.0'] and not ok, caught, ok


def main():
    all_hits, gen_counts = [], {}
    for f in SCANNED:
        all_hits += scan(f)
    for f in GENERATED:
        path = os.path.join(SEC, f)
        if os.path.exists(path):
            gen_counts[f] = len(NUM.findall(strip_comments(open(path).read())))

    viol = [h for h in all_hits if h['cat'] == 'VIOLATION']
    per_file = {}
    for h in all_hits:
        per_file.setdefault(h['file'], {}).setdefault(h['cat'], 0)
        per_file[h['file']][h['cat']] += 1

    lines = []
    A = lines.append
    A('# G3 数字字面量审计（number literal audit）')
    A('')
    A('一键复现：`python3 results/G3_number_audit.py --write`')
    A('')
    A('目的：正文里每个实验数字都必须来自 `paper/sections/numbers.tex` 的宏'
      '（由 `results/G3_gen_numbers.py` 生成）。本脚本扫描下面三个文件的'
      '**可见正文**（先剥掉 LaTeX comment），逐个数字字面量分类，'
      '要求 **非白名单的 experiment-number literal 计数 = 0**。')
    A('')
    A('扫描范围（与 `results/G1_pagebudget.md` 的结构决定一致）：'
      '`experiments.tex`、`results.tex`、`model.tex`。')
    A('')
    A('## 结论')
    A('')
    A(f'- 命中的数字字面量总数：**{len(all_hits)}**')
    A(f'- 非白名单（VIOLATION）计数：**{len(viol)}**')
    A('- `experiments.tex` 的非白名单计数：**%d**'
      % sum(1 for h in viol if h['file'] == 'experiments.tex'))
    A('')
    if viol:
        A('**未通过。** 下列位置需要改成 numbers.tex 的宏：')
        A('')
        A('| file | line | literal | context |')
        A('|---|---|---|---|')
        for h in viol:
            A('| `%s` | %d | `%s` | `%s` |'
              % (h['file'], h['line'], h['lit'], h['ctx'].replace('|', '\\|')))
    else:
        A('**通过。** 三个文件的可见正文里没有任何非白名单数字字面量。'
          '`experiments.tex` 的每个实验数字都是 numbers.tex 的宏，'
          '连 budget K 也走宏（`\\EOneKMain` 等），所以 K 白名单在该文件'
          '一次都没被用到。')
    A('')
    A('## 白名单类别（每类的理由）')
    A('')
    A('| 类别 | 含义 | 为什么不算 experiment number |')
    A('|---|---|---|')
    A('| `structure` | `\\label` / `\\ref` / `\\input` / `\\includegraphics` /'
      ' `\\begin` / `\\end` / `\\caption` 的参数 | 不是正文可见文字，是'
      ' cross-reference 与文件名 |')
    A('| `citation` | `\\citep[...]` / `\\citet[...]` 的可选参数 |'
      ' 页码或定理号 locator（如 `[Theorem~3]`），属于引用定位 |')
    A('| `length` | 带 TeX 长度单位或 `\\textwidth` 系数（`0.66\\textwidth`、'
      '`4pt`） | 排版长度，不是测量值 |')
    A('| `K value/index` | budget K 与上下标索引（`K=5`、`L_{30}`、`V_j`） |'
      ' 结构性参数与索引，不是实验测量 |')
    A('| `theory const` | 仅限 `results.tex` / `model.tex` 的 math mode 字面量'
      ' | 定理里的 closed-form 系数与模型常数，其状态由文件内注明的 oracle'
      ' 脚本（LP / sympy / 穷举）决定，不是实验数字 |')
    A('| `proper name` | 名称里的数字（%s） | 名称的一部分，不是数值 |'
      % ', '.join('`%s`' % p for p in PROPER_NAMES))
    A('')
    A('注意：`theory const` 这条白名单**不适用于** `experiments.tex`。'
      '在该文件里，任何不是 K 值的 math mode 字面量都判 VIOLATION，'
      '这正是"计数为 0"这句话有意义的原因。')
    A('')
    A('## 反向自检（negative control）')
    A('')
    A('白名单只有在遇到真违规时仍会报警才有意义，所以脚本每次运行都对'
      '一段合成文本做自检：三行含 `0.971`、`2.0`、`120`、`0.008` 的正文'
      '（其中一行是 comment，不应报），以及一段只含合法写法的文本'
      '（`K=\\ETwoKMain`、`L_{30}`、`V_0`、`0.66\\textwidth`、'
      '`\\citep[Theorem~3]{...}`、`ROUGE-1`、`\\label{...}`）。')
    A('')
    ok, caught, leaked = selftest()
    A('- 应报而报出的违规：`%s`' % '`, `'.join(caught))
    A('- 合法写法里被误报的：**%d**' % len(leaked))
    A('- 自检结论：**%s**' % ('通过' if ok else '未通过，白名单需要修'))
    A('')
    A('## 逐文件统计')
    A('')
    A('| file | 命中总数 | ' + ' | '.join(
        ['structure', 'citation', 'length', 'K value/index', 'theory const',
         'proper name', 'VIOLATION']) + ' |')
    A('|---|---|' + '---|' * 7)
    for f in SCANNED:
        d = per_file.get(f, {})
        tot = sum(d.values())
        A('| `%s` | %d | %s |' % (f, tot, ' | '.join(
            str(d.get(c, 0)) for c in
            ['structure', 'citation', 'length', 'K value/index',
             'theory const', 'proper name', 'VIOLATION'])))
    A('')
    A('## 附加扫描（不计入要求，仅供参考）')
    A('')
    A('| file | 命中总数 | VIOLATION |')
    A('|---|---|---|')
    for f in EXTRA:
        if os.path.exists(os.path.join(SEC, f)):
            hs = scan(f)
            A('| `%s` | %d | %d |'
              % (f, len(hs), sum(1 for h in hs if h['cat'] == 'VIOLATION')))
    A('')
    A('`appendix_experiments.tex` 按与正文同一条规则写（数字全部走宏），'
      '但 TASKS5 G3.4 规定的扫描范围只有上面三个文件，故单列。'
      '注意该文件是 appendix，`theory const` 白名单在这里同样不放宽：'
      '脚本对它按非 results/model 文件处理。')
    A('')
    A('## 生成文件（不计入上表，数字是脚本产出而非手打）')
    A('')
    A('| file | 数字字面量数 | 生成脚本 |')
    A('|---|---|---|')
    A('| `paper/sections/numbers.tex` | %d | `results/G3_gen_numbers.py` |'
      % gen_counts.get('numbers.tex', 0))
    A('| `paper/sections/EXP_table.tex` | %d | `results/EXP_table_build.py`'
      ' → 由 `results/G3_gen_numbers.py` 复制并把 `$\\eta^{sel}$` 改写成'
      ' `\\etasel` |' % gen_counts.get('EXP_table.tex', 0))
    A('')
    A('Table~1 的每个数字都由 `results/EXP_table_build.py` 从'
      ' `results/E{1,2,3}_rows.csv` 与 `results/E4_worst_case.csv` 重算，'
      '**算作 scripted，不算 hand-typed**。表注原样保留、一字未改：'
      'note (i) ratio 的分母是 greedy-on-$f$，是 OPT 的 upper-estimate proxy；'
      'note (ii) $\\etasel$ 只定义在正增益步上，故 $L_K$ 列的陈述只覆盖那些步，'
      '末列报 $d_t \\le 0$ 步的占比；note (iii) influence maximization 的'
      ' sign-viol. 列写 “--” 而不是测出来的 0（两个 coverage 函数结构上不可能'
      '反号）。前两条即 TASKS5 G3 指定必须保留的两句。')
    A('')
    A('## 全部命中明细')
    A('')
    A('| file | line | literal | 类别 | 理由 | context |')
    A('|---|---|---|---|---|---|')
    for h in all_hits:
        A('| `%s` | %d | `%s` | %s | %s | `%s` |'
          % (h['file'], h['line'], h['lit'], h['cat'], h['why'],
             h['ctx'].replace('|', '\\|')))
    A('')

    report = '\n'.join(lines)
    print(f'total {len(all_hits)} literals, {len(viol)} violations')
    for h in viol:
        print('  VIOLATION', h['file'], h['line'], h['lit'], '|', h['ctx'])
    if '--write' in sys.argv:
        out = os.path.join(HERE, 'G3_number_audit.md')
        with open(out, 'w') as fh:
            fh.write(report)
        print('wrote', out)
    return 1 if viol else 0


if __name__ == '__main__':
    sys.exit(main())
